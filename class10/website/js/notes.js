// Render subject notes into a container (notes.html + subject pages)
function renderSubjectNotes(containerId, subject) {
  const el = document.getElementById(containerId);
  if (!el) return;
  const notes = SUBJECT_NOTES[subject];
  if (!notes) { el.innerHTML = '<p class="muted">कृपया विषय चुनें।</p>'; return; }
  const sub = SUBJECTS[subject];
  let html = '';
  notes.forEach(n => {
    const c = n.colors || { title: '#6366f1', points: '#334155' };
    html += `
    <div class="note-topic" style="border-left-color:${c.title}">
      <div class="nt-title" style="color:${c.title}">${n.title}</div>
      <ul>
        ${n.points.map(p => `<li style="color:${c.points}">${p}</li>`).join('')}
      </ul>
      ${(n.details || []).map(d => `<div class="note-detail">${d}</div>`).join('')}
    </div>`;
  });
  el.innerHTML = html;
  if (sub) el.innerHTML = `<div class="callout callout-info mb-20">${sub.emoji} <b>${sub.name}</b> का पूरा संसार — हर टॉपिक रंग-बिरंगे, आसान भाषा में!</div>` + el.innerHTML;
}

// Render all subjects as note-cards grid
function renderAllNotes(containerId) {
  const el = document.getElementById(containerId);
  if (!el) return;
  let html = '';
  for (const s in SUBJECTS) {
    const sub = SUBJECTS[s];
    const notes = SUBJECT_NOTES[s] || [];
    const first = notes[0];
    html += `
    <div class="note-card" style="--nc-color:${sub.color}">
      <div class="note-emoji">${sub.emoji}</div>
      <h3>${sub.name}</h3>
      <p class="note-desc">${sub.desc}</p>
      ${first ? `<div class="note-topic"><div class="nt-title">${first.title}</div><ul>${first.points.slice(0,2).map(p=>`<li>${p}</li>`).join('')}</ul></div>` : ''}
      <button class="btn btn-primary btn-card mt-20" onclick="openNotesSubject('${s}')">पूरे नोट्स खोलें →</button>
    </div>`;
  }
  el.innerHTML = html;
}

// Open a notes modal / navigate to notes page
function openNotesSubject(subject) {
  location.href = 'notes.html?subject=' + subject;
}

