function renderTrigTable(el) {
  if (!el) return;
  let html = `<table class="trig-table">
    <thead><tr><th>Angle</th>${TRIG_TABLE.angles.map(a=>`<th>${a}</th>`).join('')}</tr></thead><tbody>`;
  TRIG_TABLE.rows.forEach(r => {
    html += `<tr><td><b>${r.name}</b></td>${r.values.map(v=>`<td>${v}</td>`).join('')}</tr>`;
  });
  html += `</tbody></table>
  <div class="callout callout-info mt-20">💡 ${TRIG_TABLE.tip}</div>`;
  el.innerHTML = html;
}

// Render formulas page sections
function renderFormulaSection(containerId, subject) {
  const el = document.getElementById(containerId);
  if (!el) return;
  const sections = FORMULA_DATA[subject];
  if (!sections) return;
  let html = '';
  sections.forEach(s => {
    html += `<div class="formula-section"><h2>${s.emoji} ${s.title}</h2>`;
    for (const k in s.items) {
      html += `<div class="formula-item"><div class="flabel">${k}</div><div class="fval">${s.items[k]}</div></div>`;
    }
    html += `</div>`;
  });
  el.innerHTML = html;
}