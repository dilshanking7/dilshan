function dgRender(cat) {
  const el = document.getElementById('dgContainer');
  if (!el) return;
  const items = (cat === 'all') ? DG_DATA : DG_DATA.filter(d => d.cat === cat);
  el.innerHTML = items.map(d => {
    const di = DG_DATA.indexOf(d);
    const rid = 'dgw' + di;
    const rings = d.spots.map((s, si) =>
      `<span class="dg-ring" style="left:${s.x}%;top:${s.y}%" data-i="${si}"></span>`).join('');
    const chips = d.parts.map((p, pi) =>
      `<button class="dg-chip" data-i="${pi}">${dgEscape(p.name.split('(')[0].trim())}</button>`).join('');
    return `
    <div class="dg-card" data-id="${rid}">
      <h3 class="dg-title">${d.title}</h3>
      <div class="dg-flow">➜ ${dgEscape(d.flow)}</div>
      <div class="dg-imgwrap" id="${rid}">
        <img class="dg-img" src="${dgEscape(d.img)}" alt="${dgEscape(d.alt)}" loading="lazy"
             onclick="dgNext('${rid}', event)">
        ${rings}
      </div>
      <div class="dg-chips">${chips}</div>
      <div class="dg-fn" data-hint="👇 ऊपर diagram पर किसी भी हिस्से को छूकर देखो — या नीचे किसी chip पर click करो — बड़े अक्षरों में उस part का काम खुल जाएगा!">
        <div class="dg-fn-sub">👇 किसी भाग पर click करो</div>
      </div>
      ${d.note ? `<p class="dg-note">💡 ${dgEscape(d.note)}</p>` : ''}
    </div>`;
  }).join('');
}

// Select a part by index within a card id
function dgSelect(rid, idx) {
  const wrap = document.getElementById(rid);
  if (!wrap) return;
  const card = wrap.closest('.dg-card');
  const cardIdx = Number(card.dataset.id.replace('dgw', ''));
  const d = DG_DATA[cardIdx];
  const fnBox = card.querySelector('.dg-fn');
  const chipBtn = card.querySelectorAll('.dg-chip')[idx];
  const rings = wrap.querySelectorAll('.dg-ring');

  const already = wrap.querySelector('.dg-ring.active') &&
                 Number(wrap.querySelector('.dg-ring.active').dataset.i) === idx;
  wrap.querySelectorAll('.dg-ring').forEach(r => r.classList.remove('active'));
  card.querySelectorAll('.dg-chip').forEach(c => c.classList.remove('active'));

  if (already) {
    fnBox.innerHTML = `<div class="dg-fn-sub">👇 किसी भाग पर click करो</div>`;
    return;
  }
  rings[idx].classList.add('active');
  if (chipBtn) chipBtn.classList.add('active');
  fnBox.innerHTML = `<div class="dg-fn-name">${dgEscape(d.parts[idx].name)}</div>
                     <div class="dg-fn-text">${dgEscape(d.parts[idx].fn)}</div>`;
  fnBox.scrollIntoView({ behavior: 'smooth', block: 'nearest' });
}

function dgNext(rid, ev) {
  const wrap = document.getElementById(rid);
  if (!wrap) return;
  const card = wrap.closest('.dg-card');
  const cardIdx = Number(card.dataset.id.replace('dgw', ''));
  const total = DG_DATA[cardIdx].parts.length;
  const cur = [...wrap.querySelectorAll('.dg-ring')].findIndex(r => r.classList.contains('active'));
  dgSelect(rid, (cur + 1) % total);
}

function dgTab(cat, btn) {
  document.querySelectorAll('.dg-tab').forEach(t => t.classList.remove('active'));
  if (btn) btn.classList.add('active');
  dgRender(cat);
}

if (typeof document !== 'undefined') {
  document.addEventListener('DOMContentLoaded', () => {
    dgRender('bio');
    document.addEventListener('click', ev => {
      const ring = ev.target.closest('.dg-ring');
      if (ring) {
        const wrap = ring.closest('.dg-imgwrap');
        dgSelect(wrap.id, Number(ring.dataset.i));
      }
      const chip = ev.target.closest('.dg-chip');
      if (chip) {
        const card = chip.closest('.dg-card');
        const wrap = card.querySelector('.dg-imgwrap');
        dgSelect(wrap.id, Number(chip.dataset.i));
      }
    });
  });
}

