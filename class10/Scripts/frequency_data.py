def frequency_sections():
    groups = {}
    for subj, q, times, year in FREQUENCY_ANALYSIS:
        groups.setdefault(subj, []).append((q, times, year))
    sections = []
    order = ["Hindi", "English", "Maths", "Science", "History", "Geography", "Civics", "Economics"]
    for subj in order:
        if subj not in groups:
            continue
        items = [('S', f"{subj} - सबसे अधिक बार पूछे गए प्रश्न (Most Repeated)")]
        # sort by times desc
        for q, times, year in sorted(groups[subj], key=lambda x: -x[1]):
            items.append(('Q', f"{q}  (कुल {times} बार आया)"))
            items.append(('A', f"पिछले 5 वर्षों में: {year}"))
        sections.append((f"{subj} - FREQUENCY ANALYSIS (प्रश्न आवृत्ति विश्लेषण)", items))
    # summary
    summary_items = [('S', "बोर्ड परीक्षा हेतु सबसे महत्वपूर्ण विषय (टॉपिक)")]
    for subj, q, times, year in sorted(FREQUENCY_ANALYSIS, key=lambda x: -x[2]):
        if times >= 5:
            summary_items.append(('Q', f"[{subj}] {q} - {times} बार"))
    sections.insert(0, ("सबसे अधिक बार आने वाले प्रश्न (Top Repeated Questions)", summary_items))
    return sections
